export function fbStrings(lang: string | undefined): FbStrings {
  return lang?.startsWith('en') ? en : ru;
}

/** The tool's words in the app's language (follows a change of language). */
export function useFbStrings(): FbStrings {
  const { i18n } = useTranslation();
  return fbStrings(i18n.language);
}
